#!/usr/bin/env python3
"""Render the report-only localization snapshot from existing app translations.

Prints source (or an apply_patch patch); never edits files or reads live data.
The extension cannot import the app's actor-bound localization/state helpers,
so it gets a verbatim copy of the pure Shared/AppLanguageMatching.swift matcher
and a table for each published language (the original eight plus every 2.0
language marked complete; pending languages fall back to English).
"""
import json
from pathlib import Path
import re
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import app_languages as L  # noqa: E402

ROOT = L.ROOT
STRING = r'"((?:[^"\\]|\\.)*)"'
RTL = ('ar', 'he', 'ur')


def report_keys():
    view = '\n'.join((ROOT / 'LatchReport' / name).read_text() for name in
                     ['UsageInsightsView.swift', 'UsageTrendsView.swift', 'LimitsUsageView.swift'])
    # Literal helper arguments (cards, footnotes, formats) and figure titles.
    keys = {json.loads('"' + key + '"') for key in re.findall(
        r'\b(?:insightsText|card|footnote|format|pageButton)\(\s*' + STRING, view)}
    keys.update(json.loads('"' + key + '"') for key in re.findall(r'title:\s*' + STRING, view))
    # Pure display logic (UsageFormat, segment names) hands keys to the views
    # through `translate`/`format` calls and returned literals.
    logic = '\n'.join((ROOT / 'LatchReport' / name).read_text() for name in
                      ['UsageFormat.swift', 'UsageDashboardPresentation.swift'])
    logic = re.sub(r'//[^\n]*', '', logic)
    found = re.findall(r'(?:\btranslate\(|\bformat\(|\breturn|=)\s*' + STRING, logic)
    keys.update(key for key in (json.loads('"' + value + '"') for value in found)
                if re.search(r'[A-Za-z%]', key) and not re.fullmatch(r'[a-z]+(?:\.[a-z]+)+', key))
    return keys


def matcher():
    source = (ROOT / 'Shared/AppLanguageMatching.swift').read_text()
    return source.split('// BEGIN APP LANGUAGE MATCHING\n', 1)[1].split('// END APP LANGUAGE MATCHING', 1)[0]


def render():
    keys = report_keys()
    tables = L.complete_tables()
    supported = ', '.join(json.dumps(code) for code in L.CODES)
    lines = [
        '// Generated by Tests/GenerateUsageLocalization.py; app translations are the source.',
        '// Read-only preferences; no measured usage leaves this report extension.',
        'import Foundation', '',
        '/// The in-app language, matched like AppLanguage.current in the app.',
        'nonisolated func reportLanguageCode() -> String {',
        f'    let supported: Set<String> = [{supported}]',
        '    if let saved = UserDefaults(suiteName: AppGroup.id)?.string(forKey: "latch.language"),',
        '       supported.contains(saved) { return saved }',
        '    return AppLanguageMatching.code(preferred: Locale.preferredLanguages, supported: supported)',
        '}', '',
        '/// Arabic, Hebrew and Urdu mirror the layout; charts and clocks never do.',
        'nonisolated func reportIsRightToLeft() -> Bool {',
        f'    [{", ".join(json.dumps(c) for c in RTL)}].contains(reportLanguageCode())',
        '}', '',
        '// Copied verbatim from Shared/AppLanguageMatching.swift.',
        matcher().rstrip('\n'), '',
        'nonisolated func insightsText(_ key: String) -> String {',
        '    switch reportLanguageCode() {',
    ]
    for code, table in tables.items():
        table = dict(table)
        # Numeric/date placeholders need no language-specific text.
        table.setdefault('%@ – %@', '%@ – %@')
        missing = keys - table.keys()
        if missing:
            raise ValueError(f'{code}: missing report keys {sorted(missing)}')
        lines += [f'    case "{code}":', f'        // LANGUAGE {code}',
                  '        let table: [String: String] = [']
        for key in sorted(keys):
            lines.append('            ' + json.dumps(key, ensure_ascii=False) + ': '
                         + json.dumps(table[key], ensure_ascii=False) + ',')
        lines += ['        ]', '        // END LANGUAGE', '        return table[key] ?? key']
    lines += ['    default: return key', '    }', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    source = render()
    target = ROOT / 'LatchReport/UsageInsightsLocalization.swift'
    if '--check' in sys.argv:
        assert target.read_text() == source, 'Regenerate the extension-local translation snapshot'
        published = len(L.complete_tables())
        print(f'Usage report localization snapshot matches {len(report_keys())} keys × {published} languages'
              f' ({L.publication_note(published)}); matcher copied verbatim')
    elif '--patch' in sys.argv:
        if target.exists():
            print('*** Begin Patch\n*** Update File: ' + str(target) + '\n@@')
            print('\n'.join('-' + line for line in target.read_text().splitlines()))
        else:
            print('*** Begin Patch\n*** Add File: ' + str(target))
        print('\n'.join('+' + line for line in source.splitlines()))
        print('*** End Patch')
    else:
        print(source, end='')
