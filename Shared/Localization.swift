//
//  Localization.swift
//  In-app language switching. Strings are written in English in code and
//  looked up in the table below; missing keys fall back to English.
//  Stored in the app group so the extensions localize too.
//

import Foundation

enum AppLanguage: String, CaseIterable, Identifiable {
    case english = "en"
    case spanish = "es"
    case german = "de"
    case french = "fr"
    case portuguese = "pt"
    case polish = "pl"
    case turkish = "tr"
    case hindi = "hi"

    var id: String { rawValue }
    var label: String {
        switch self {
        case .english: return "English"
        case .spanish: return "Español"
        case .german: return "Deutsch"
        case .french: return "Français"
        case .portuguese: return "Português"
        case .polish: return "Polski"
        case .turkish: return "Türkçe"
        case .hindi: return "हिन्दी"
        }
    }

    var locale: Locale { Locale(identifier: rawValue) }

    /// English and Spanish are the original, reviewed localizations. The newer
    /// translations invite feedback after the user explicitly commits them.
    var isBetaTranslation: Bool {
        self != .english && self != .spanish
    }

    static var current: AppLanguage {
        get {
            // An explicit in-app choice always wins.
            if let saved = SharedStore.defaults.string(forKey: "latch.language"),
               let lang = AppLanguage(rawValue: saved) {
                return lang
            }
            // Otherwise follow the device when Demora supports its preferred
            // language, falling back to English.
            let preferred = Locale.preferredLanguages.first ?? "en"
            let code = Locale(identifier: preferred).language.languageCode?
                .identifier ?? String(preferred.prefix(2))
            return AppLanguage(rawValue: code) ?? .english
        }
        set {
            SharedStore.defaults.set(newValue.rawValue, forKey: "latch.language")
            DemoraWidgetSnapshot.publish(state: SharedStore.loadState())
            DemoraNotifications.rescheduleFreeBoundaries(state: SharedStore.loadState())
        }
    }
}

func tr(_ key: String) -> String {
    let table: [String: String]?
    switch AppLanguage.current {
    case .english: table = nil
    case .spanish: table = spanishStrings
    case .german: table = germanStrings
    case .french: table = frenchStrings
    case .portuguese: table = portugueseStrings
    case .polish: table = polishStrings
    case .turkish: table = turkishStrings
    case .hindi: table = hindiStrings
    }
    return table?[key] ?? key
}

